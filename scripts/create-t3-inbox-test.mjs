import fs from 'node:fs';import path from 'node:path';
import {command,write,root,setup,parse} from './umka-t3code.mjs';
import {tick} from './umka-t3-runtime.mjs';
if(!process.argv[2]) throw new Error('Usage: node scripts/create-t3-inbox-test.mjs NEW_DIRECTORY');
const dir=path.resolve(process.argv[2]),home=path.join(dir,'home');
if(fs.existsSync(dir))throw new Error('Fixture exists');
const o=parse(['apply','--home',home,'--instance','inbox-test']);
setup({...o,mode:'apply'});
const bd=args=>command('bd',['-C',home,...args]);
const epic=JSON.parse(bd(['create','Disposable inbox decision','--type','epic','-l','loop','-d','A synthetic setup checkpoint. No repository or source ticket. The proposal is only to record that inbox replies work. No product decision or code work.','--json']));bd(['note',epic.id,'channel: cli']);
const item=JSON.parse(bd(['create','checkpoint: approve proposal','--parent',epic.id,'-l','phase:approve-proposal,checkpoint','-d','Approve the synthetic inbox test proposal: record that a human can answer in T3. No ADRs or glossary changes. Do you approve this test proposal? Recommended answer: yes. Evidence: this setup fixture only. To answer: use the Umka inbox.','--json']));
write(path.join(dir,'state.json'),{dir,home,epicId:epic.id,itemId:item.id});
console.log(tick(o));
